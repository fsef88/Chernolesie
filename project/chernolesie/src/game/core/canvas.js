 // VIEW_H — высота кадра в мировых px, VIEW_W_MAX — предел ширины для ультравайдов.
 // 1133 (10 ростов героя, как в VS) оказалось тесно: на широком мониторе
 // 2560x1215 упирался именно ПРЕДЕЛ ШИРИНЫ, а не высоты, и кадр сплющивало
 // до 19.4x9.2 роста. Подняты оба: теперь 22.9x10.9 роста на том же окне.
