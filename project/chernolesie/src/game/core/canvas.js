 // съёмка», герой в одну пятнадцатую экрана.
 const VIEW_H=1250, VIEW_W_MAX=2600;
 let _z=cssH/VIEW_H;
 if(cssW/_z>VIEW_W_MAX)_z=cssW/VIEW_W_MAX;
 ZOOM=Math.max(0.25,Math.min(2.5,_z));
