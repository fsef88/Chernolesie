 // при реальном отношении площадей 13 — поле выглядело пустым.
 //
 // Ориентир взят из VS: пиксель-перфект разрешения игры (960x640, 1200x800,
 // 1440x960, 1920x1280) — это 2x, 2.5x, 3x и 4x от кадра 480x320 при спрайтах
 // 32x32. То есть по вертикали в кадр входит 10 ростов персонажа.
