  //  кадр тогда, когда успеет: то через две развёртки, то через три, то через
  //  четыре. Средний FPS при этом выглядит приличным, а картинка идёт рывками,
  //  потому что рывок делает НЕРОВНОСТЬ, а не среднее.
  //
  //  Лечится не ускорением, а расписанием: рисуем строго через N развёрток.
  //  Тогда кадр живёт одинаково долго, и 60 ровных на 120 Гц читаются как
