// Лечим множителем скорости от обзора. Проверил арифметику: видимая площадь растёт
// как 1/zoom², поэтому корень из неё — это ровно 1/zoom, то есть компенсация полная,
// а не частичная (сначала описал её как компромисс — это было неверно).
// Что это значит на деле: скорость на экране одинаковая при любом обзоре — 200 px/с,
