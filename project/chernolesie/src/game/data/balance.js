// v5.76: ЕДИНАЯ ФОРМУЛА БРОНИ. Было два разных множителя в двух путях урона:
// (1-armor*0.02) у выстрелов шутеров и (1-armor*0.5) в контакте. Первый превращал
// «+15% броня» в 0.3% — узел Кузницы не работал против дальнего урона.
// v5.87: было 1-a*0.5, то есть ВДВОЕ меньше обещанного. «Руна щита» с текстом
// «+20% броня» давала 10%, узел Кузницы gd3 «+15% броня» — 7.5% за уровень.
// Оба описания трактуют armor как прямую долю снижения урона, поэтому делаем
// формулу буквальной. Потолок вложений: gd3 макс (+0.45) + руна (+0.2) = 0.65,
// то есть 35% получаемого урона — ровно нижний порог, дальше не уходит.
// v7.36: пол брони поднят с 0.35 до 0.62. Процентная броня, режущая 65%, гасит
// рост урона врага ровно в тот момент, когда он начинает работать: множитель
// ×5 к 25-й минуте превращался бы в ×1.75. У эталона броня плоская и мелкая —
// 3 от меты плюс 5 от пассивки, то есть −8 против урона 20. Это −40% и только в
// конце забега, когда урон уже вырос; в начале те же 8 от урона 10 весят больше.
// Пол 0.62 повторяет эталонный потолок снижения, оставаясь множителем.
