const AFFIX_LIST=['furious','frost','tanky','booming'];
const AFFIX_AURA={furious:'rgba(255,80,60,',frost:'rgba(120,200,255,',tanky:'rgba(255,215,90,',booming:'rgba(255,150,50,'};
const AFFIX_NAMES={furious:'Яростный',frost:'Студёный',tanky:'Живучий',booming:'Взрывной'};
function spawnElite(){
 // Спавн от ЦЕНТРА КАМЕРЫ (cam.x+W/2, cam.y+H/2), а не от P.x/P.y
 // Иначе при упоре камеры в край мира элита появится в центре экрана.
 // + защита clamp в пределы мира [0..WORLD]
 const cx=cam.x+W/2,cy=cam.y+H/2;
 // v6.33: было rad=max(W,H)*0.85+200 — на широком обзоре это 2920 единиц,
 // то есть 72 секунды хода при интервале спавна 75 с. Элита не доходила до
 // игрока НИКОГДА: замер честным ботом за 11 минут — 28 заспавнено, 0 убито,
 // 0 сундуков, 0 эволюций, 0 синергий. Вся ветка контента была мертва.
 // Ставим её чуть за краем экрана: появление по-прежнему вне поля зрения,
 // но охота занимает секунды, а не минуты.
 const a=srnd(0,TAU),rad=Math.max(W,H)*0.55+120,b=ETYPES.upyr;
 let sx=cx+Math.cos(a)*rad,sy=cy+Math.sin(a)*rad;
 // Защита от выхода за границы мира
 sx=clamp(sx,0,WORLD);sy=clamp(sy,0,WORLD);
 // (#10) safeNum — битый localStorage мог дать diffMul=NaN → враг NaN HP
 // v5.89: HP элиты были ЖЁСТКИМИ на весь забег (240), тогда как рядовые враги
 // растут через enemyHpMul до ×8, а урон игрока — в разы. Элита на 25:00 была
 // слабее обычного упыря того же времени, хотя именно она даёт сундук и
 // эволюцию. Масштабируем той же формулой, что уже применена к Лешему-Вожаку —
 // это единственный спавнер из пяти, где масштаб был доделан.
 // v6.62: аффикс элиты — через seedRandom, чтобы Daily Run был детерминирован
 const affix=AFFIX_LIST[Math.floor(seedRandom()*AFFIX_LIST.length)];
 let ehp=safeNum(b.hp*8*diffMul*(1+0.05*Math.floor(time/120)),240);
 if(affix==='tanky')ehp*=1.5;
 // hasRelic: флаг — даст реликвию ПОСЛЕ убийства, не на спавне
 acquireEnemy({...b,x:sx,y:sy,hp:ehp,maxhp:ehp,type:'upyr',elite:true,affix:affix,drawH:b.drawH*1.3,at:0,flash:0,slow:1,kx:0,ky:0,hitT:0,wasInRange:false,boltT:0,frozen:0,poisoned:0,zigzag:a,zigzagT:0,ai:'tank',dmgMod:1.5,fireT:0,hasRelic:seedRandom()<(0.35+(P.luck||0))});
 log('⚠ '+AFFIX_NAMES[affix]+' элитный упырь!', 'warn');   // v5.89: было «тролль» — элита это ETYPES.upyr, троллей в бестиарии нет
}
