#!/usr/bin/env python3
# ============================================================
#  gen-ground.py — процедурный тайл земли для боевого поля.
#
#  Прежний тайл (фотографический ковёр из корней) глушил спрайты: очень
#  контрастная тёплая органика того же масштаба, что и враг в 40 px.
#  Грейдингом это не лечится — проверено: умножение и десатурация двигают
#  тон на сотые доли, а высокочастотный рисунок остаётся.
#
#  Здесь тайл строится, а не красится. Шум фильтруется в частотной области,
#  поэтому результат ПЕРИОДИЧЕН ПО ПОСТРОЕНИЮ: DFT трактует картинку как
#  бесконечно повторяющуюся, и шва на стыке не существует в принципе —
#  в отличие от нейросетевой текстуры, которую пришлось бы сводить вручную.
#
#  Рисунок намеренно низкочастотный: крупные мягкие пятна наста поверх
#  тёмной мёрзлой земли плюс мелкое зерно. Читаемость целиком отдана
#  спрайтам, земля не претендует ни на что.
#
#  Запуск: python3 tools/gen-ground.py [seed]
# ============================================================
import sys
import numpy as np
from PIL import Image

N = 768
SEED = int(sys.argv[1]) if len(sys.argv) > 1 else 20260807
rng = np.random.default_rng(SEED)

# радиальные частоты для гауссова фильтра
fy = np.fft.fftfreq(N)[:, None]
fx = np.fft.fftfreq(N)[None, :]
r2 = fy ** 2 + fx ** 2


def band(sigma_px):
    """Изотропный низкочастотный шум с характерным размером sigma_px."""
    w = np.fft.fft2(rng.normal(size=(N, N)))
    # гаусс в частотной области = гаусс-размытие в пространственной
    w *= np.exp(-2 * (np.pi * sigma_px) ** 2 * r2)
    out = np.real(np.fft.ifft2(w))
    return out / (out.std() + 1e-9)


def norm01(a):
    return (a - a.min()) / (a.max() - a.min() + 1e-9)


# Три масштаба: крупные наносы, средние языки, лёгкая неровность.
blobs = 1.00 * band(58) + 0.55 * band(26) + 0.22 * band(11)
blobs = norm01(blobs)

# Пятна должны быть именно пятнами, а не плавным градиентом: смягчённая
# ступенька разводит наст и землю, оставляя мягкую кромку.
t = np.clip((blobs - 0.42) / 0.34, 0, 1)
t = t * t * (3 - 2 * t)                     # smoothstep

# Мелкое зерно — фактура, но НЕ рисунок: амплитуда мала, размер меньше врага.
grain = norm01(band(1.3)) - 0.5
t = np.clip(t + 0.055 * grain, 0, 1)

# Палитра: мёрзлая земля -> наст. Обе холодные, синий канал старший.
DARK = np.array([0.105, 0.125, 0.150])
LITE = np.array([0.300, 0.340, 0.395])
img = DARK + (LITE - DARK) * t[..., None]

# Очень слабая крупная неоднородность яркости, чтобы поле не было ровным
img *= (0.94 + 0.12 * norm01(band(120)))[..., None]

img = np.clip(img, 0, 1)
Image.fromarray((img * 255 + 0.5).astype(np.uint8)).save(
    'assets/art/world/ground-winter.webp', 'WEBP', quality=90, method=6)

# --- отчёт: шов проверяем сравнением противоположных кромок ---
a = img
seam_x = np.abs(a[:, 0] - a[:, -1]).mean()
seam_y = np.abs(a[0, :] - a[-1, :]).mean()
inner = np.abs(a[:, 1:] - a[:, :-1]).mean()
mx = a.max(axis=2); mn = a.min(axis=2)
sat = np.where(mx > 0, (mx - mn) / np.maximum(mx, 1e-9), 0)
print('тайл %dx%d  seed %d' % (N, N, SEED))
print('  R%.2f G%.2f B%.2f   B-R %+.2f   насыщ %.2f   ярк %.2f   контраст(s) %.3f'
      % (a[..., 0].mean(), a[..., 1].mean(), a[..., 2].mean(),
         a[..., 2].mean() - a[..., 0].mean(), sat.mean(), mx.mean(), a.mean(axis=2).std()))
print('  разрыв на стыке: по X %.5f, по Y %.5f (обычный перепад между соседними столбцами %.5f)'
      % (seam_x, seam_y, inner))
